#!/bin/bash
# Regenerates app/Sources/Portico/Resources/editor.js, the viewer's editor
# (v0.20 §5): installs the pinned packages from package-lock.json, runs the
# editor's tests, bundles src/editor.ts with esbuild, and writes the bundle
# with its hash line and licence header. The app build never runs this; the
# bundle is committed.
#
# The first line of the bundle is
#   /* portico-editor <sha256> */
# where <sha256> is the SHA-256 of the bytes of every src/*.ts file, in
# byte order of their names, then build.sh, bundle.mjs and package-lock.json. A stale bundle
# (sources changed, bundle not rebuilt) fails tests/test_distribution.py.
#
# NODE and NPM may name the tools to use; otherwise Homebrew's are preferred
# over whatever `npm` is first on PATH.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
out_dir="$here/.out"
target="$repo/app/Sources/Portico/Resources/editor.js"

pick() {
    local var="$1" name="$2"
    if [[ -n "${!var:-}" ]]; then
        echo "${!var}"
    elif [[ -x "/opt/homebrew/bin/$name" ]]; then
        echo "/opt/homebrew/bin/$name"
    else
        command -v "$name"
    fi
}
NODE="$(pick NODE node)"
NPM="$(pick NPM npm)"
export PATH="$(dirname "$NODE"):$PATH"

cd "$here"
echo "editor: installing pinned packages"
"$NPM" ci --ignore-scripts --no-audit --no-fund --loglevel=error

echo "editor: tests"
"$NODE" --test test/*.test.ts

echo "editor: bundling"
rm -rf "$out_dir"
mkdir -p "$out_dir"
"$NODE" bundle.mjs "$out_dir/body.js" "$out_dir/meta.json"

# The sources the bundle is made from: the editor's TypeScript (byte order of
# file names), this script, bundle.mjs, then the lock file.
hash="$(cat $(printf '%s\n' src/*.ts | LC_ALL=C sort) build.sh bundle.mjs package-lock.json | shasum -a 256 | cut -d' ' -f1)"

# The licence header: every package that ended up in the bundle, with its
# version, licence and copyright line, then the licence text. A package whose
# licence is not MIT, or whose text differs from the shared MIT text (its
# copyright line aside), has its own text printed in full.
"$NODE" -e '
const fs = require("fs");
const meta = require(process.argv[1]);
const names = new Set();
for (const input of Object.keys(meta.inputs)) {
  const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (m) names.add(m[1]);
}
const bodyOf = (text) => text.split(/\r?\n/).filter((l) => !/^\s*copyright/i.test(l)).join("\n").replace(/\n{3,}/g, "\n\n").trim();
const licenceFile = (dir) => fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
const shared = bodyOf(fs.readFileSync("node_modules/@codemirror/state/LICENSE", "utf8"));
const lines = [];
const own = [];
for (const name of [...names].sort()) {
  const dir = "node_modules/" + name;
  const pkg = require("./" + dir + "/package.json");
  if (pkg.license !== "MIT") { console.error("editor: " + name + " is not MIT (" + pkg.license + ")"); process.exit(1); }
  const file = licenceFile(dir);
  const text = file ? fs.readFileSync(dir + "/" + file, "utf8") : "";
  const author = typeof pkg.author === "string" ? pkg.author : pkg.author ? [pkg.author.name, pkg.author.email && "<" + pkg.author.email + ">"].filter(Boolean).join(" ") : "";
  const copyright = (text.split(/\r?\n/).find((l) => /^\s*copyright/i.test(l)) || (author ? "Copyright " + author : "")).trim();
  if (!copyright) { console.error("editor: no copyright line for " + name); process.exit(1); }
  lines.push(name + " " + pkg.version + " (" + pkg.license + "): " + copyright);
  if (!text || bodyOf(text) !== shared) own.push([name, text || "MIT, see package.json"]);
}
const out = [];
out.push("Bundled packages:");
for (const l of lines) out.push("  " + l);
out.push("");
out.push("Each is under the MIT licence below, with its copyright line above:");
out.push("");
out.push(shared);
for (const [name, text] of own) { out.push(""); out.push(name + ":"); out.push(text.trim()); }
fs.writeFileSync(process.argv[2], out.join("\n") + "\n");
' "$out_dir/meta.json" "$out_dir/licences.txt"

{
    echo "/* portico-editor $hash */"
    echo "/*"
    echo " * Portico's editor: CodeMirror 6 with Portico's live preview."
    echo " * Generated by app/Editor/build.sh; do not edit. See THIRD_PARTY.md."
    echo " *"
    sed 's/^/ * /; s/ *$//; s#\*/#* /#g' "$out_dir/licences.txt"
    echo " */"
    cat "$out_dir/body.js"
} > "$out_dir/editor.js"

# The public repo never names a deployment: the same list as the
# distribution test, read from it, checked against the bundle.
forbidden="$("$NODE" -e '
const src = require("fs").readFileSync(process.argv[1], "utf8");
const block = /FORBIDDEN = \[([\s\S]*?)\]/.exec(src);
if (!block) { console.error("editor: FORBIDDEN list not found"); process.exit(1); }
const words = [...block[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
if (words.length === 0) { console.error("editor: FORBIDDEN list is empty"); process.exit(1); }
console.log(words.join("\n"));' "$repo/tests/test_distribution.py")"
found=0
while IFS= read -r word; do
    if grep -qiF -- "$word" "$out_dir/editor.js"; then
        echo "editor: the bundle contains a forbidden name: $word" >&2
        found=1
    fi
done <<< "$forbidden"
# The page inlines the bundle in a <script> element.
if grep -qi '</script' "$out_dir/editor.js"; then
    echo "editor: the bundle contains </script" >&2
    found=1
fi
[[ $found -eq 0 ]] || exit 1

mv "$out_dir/editor.js" "$target"
rm -rf "$out_dir"
echo "editor: wrote $(basename "$target") ($(wc -c < "$target" | tr -d ' ') bytes, $hash)"
